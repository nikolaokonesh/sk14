def norm(value)
  value.to_s.downcase.strip.gsub("ё", "е")
end

def upsert_district!(slug:, name:, emoji:, time_zone:, position:)
  district = District.find_or_initialize_by(slug: slug)
  district.assign_attributes(name: name, emoji: emoji, time_zone: time_zone, position: position)
  district.save!
end

def upsert_category!(slug:, name:, emoji:, position:)
  category = Category.find_or_initialize_by(slug: slug)
  category.assign_attributes(name: name, emoji: emoji, position: position)
  category.save!
end

def add_category_keywords!(category_slug, words)
  category = Category.find_by!(slug: category_slug)
  words.each do |word, weight|
    keyword = CategoryKeyword.find_or_initialize_by(category: category, word: norm(word))
    keyword.weight = weight
    keyword.save!
  end
end

def add_classifier!(kind:, value:, words:)
  words.each do |word, weight|
    keyword = ClassifierKeyword.find_or_initialize_by(kind: kind.to_s, value: value.to_s, word: norm(word))
    keyword.weight = weight
    keyword.save!
  end
end

